CREATE TABLE IF NOT EXISTS Users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(64) NOT NULL,
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash VARCHAR(256) NOT NULL
);

CREATE TABLE IF NOT EXISTS Stocks (
  symbol VARCHAR(16) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS Portfolios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES Users(id),
  label VARCHAR(64) NOT NULL,
  cash_balance NUMERIC(20, 4) NOT NULL DEFAULT 0,
  CHECK (cash_balance >= 0)
);

CREATE TABLE IF NOT EXISTS PortfolioHoldings (
  portfolio_id INTEGER NOT NULL REFERENCES Portfolios(id),
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  num_shares NUMERIC(20, 6) NOT NULL,
  PRIMARY KEY (portfolio_id, stock_symbol),
  CHECK (num_shares > 0)
);


CREATE TABLE IF NOT EXISTS CashTransactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  portfolio_id INTEGER NOT NULL REFERENCES Portfolios(id),
  cash_transaction_type VARCHAR(16) NOT NULL,
  amount NUMERIC(20, 4) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (cash_transaction_type IN ('deposit', 'withdrawal', 'transfer_in', 'transfer_out')),
  CHECK (amount > 0)
);

CREATE TABLE IF NOT EXISTS StockTransactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  portfolio_id INTEGER NOT NULL REFERENCES Portfolios(id),
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  stock_transaction_type VARCHAR(16) NOT NULL,
  num_shares NUMERIC(20, 6) NOT NULL,
  share_price NUMERIC(20, 6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (stock_transaction_type IN ('buy', 'sell')),
  CHECK (num_shares > 0),
  CHECK (share_price >= 0)
);

CREATE TABLE IF NOT EXISTS HistData (
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  at_date DATE NOT NULL,
  open_price DOUBLE PRECISION,
  close_price DOUBLE PRECISION NOT NULL,
  high_price DOUBLE PRECISION,
  low_price DOUBLE PRECISION,
  trade_volume BIGINT NOT NULL,
  PRIMARY KEY (stock_symbol, at_date),
  CHECK (open_price >= 0),
  CHECK (close_price >= 0),
  CHECK (high_price >= 0),
  CHECK (low_price >= 0),
  CHECK (trade_volume >= 0)
);

CREATE TABLE IF NOT EXISTS NewData (
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  at_date DATE NOT NULL,
  open_price DOUBLE PRECISION,
  close_price DOUBLE PRECISION NOT NULL,
  high_price DOUBLE PRECISION,
  low_price DOUBLE PRECISION,
  trade_volume BIGINT NOT NULL,
  PRIMARY KEY (stock_symbol, at_date),
  CHECK (open_price >= 0),
  CHECK (close_price >= 0),
  CHECK (high_price >= 0),
  CHECK (low_price >= 0),
  CHECK (trade_volume >= 0)
);

CREATE TABLE IF NOT EXISTS StockStats (
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  from_date DATE NOT NULL,
  to_date DATE NOT NULL,
  coefficient_of_variance DOUBLE PRECISION NOT NULL,
  beta DOUBLE PRECISION NOT NULL,
  computed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (stock_symbol, from_date, to_date),
  CHECK (from_date <= to_date)
);

CREATE TABLE IF NOT EXISTS StockPairStats (
  low_stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  high_stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  from_date DATE NOT NULL,
  to_date DATE NOT NULL,
  covariance DOUBLE PRECISION NOT NULL,
  correlation DOUBLE PRECISION NOT NULL,
  computed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (low_stock_symbol, high_stock_symbol, from_date, to_date),
  CHECK (low_stock_symbol <= high_stock_symbol),
  CHECK (from_date <= to_date)
);
