import connect, { sql } from "@databases/pg";

const db = connect();

/*
CREATE TABLE IF NOT EXISTS Portfolios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES Users(id),
  label VARCHAR(64) NOT NULL,
  cash_balance NUMERIC(20, 4) NOT NULL DEFAULT 0,
  CHECK (cash_balance >= 0)
);

CREATE TABLE IF NOT EXISTS PortfolioHoldings (
  portfolio_id INTEGER NOT NULL REFERENCES Portfolios(id) ON DELETE CASCADE,
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  num_shares NUMERIC(20, 6) NOT NULL,
  PRIMARY KEY (portfolio_id, stock_symbol),
  CHECK (num_shares > 0)
);
*/

export async function getPortfolios(user_id) {
  return await db.query(sql`
    SELECT id, label
    FROM Portfolios
    WHERE user_id=${user_id};
  `);
}

export async function getPortfolio(user_id, portfolio_id) {
  return await db.tx(async (tx) => {
    const owned = await tx.query(sql`
        SELECT id
        FROM Portfolios
        WHERE 
          user_id = ${user_id} AND
          id = ${portfolio_id};
      `);

    if (owned.length !== 1) {
      throw new Error("Invalid portfolio");
    }
    return await tx.query(sql`
      SELECT p.label, p.cash_balance, h.stock_symbol, h.num_shares
      FROM Portfolios p 
      LEFT JOIN PortFolioHoldings h 
      ON p.id = h.portfolio_id
      WHERE 
        p.id=${portfolio_id} AND
        p.user_id = ${user_id};
      `);
  });
}

export async function createPortfolio(user_id, label) {
  return await db.query(sql`
    INSERT INTO Portfolios (user_id, label)
    VALUES (${user_id}, ${label});
  `);
}

export async function deletePortfolio(user_id, portfolio_id) {
  return await db.tx(async (tx) => {
    const owned = await tx.query(sql`
        SELECT id
        FROM Portfolios
        WHERE 
          user_id = ${user_id} AND
          id = ${portfolio_id};
      `);

    if (owned.length !== 1) {
      throw new Error("Invalid portfolio");
    }

    return await tx.query(sql`
      DELETE FROM Portfolios 
      WHERE 
        id = ${portfolio_id} AND 
        user_id = ${user_id};
    `);
  });
}
