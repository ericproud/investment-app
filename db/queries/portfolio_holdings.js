import connect, { sql } from "@databases/pg";

const db = connect();

/*
CREATE TABLE IF NOT EXISTS Portfolios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES Users(id),
  label VARCHAR(64) NOT NULL,
  cash_balance NUMERIC(20, 4) NOT NULL DEFAULT 0,
  CHECK (cash_balance >= 0)
);

CREATE TABLE IF NOT EXISTS PortfolioHoldings (
  portfolio_id INTEGER NOT NULL REFERENCES Portfolios(id),
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  num_shares NUMERIC(20, 6) NOT NULL,
  PRIMARY KEY (portfolio_id, stock_symbol),
  CHECK (num_shares > 0)
);
*/

export async function getPortfolioHoldings(user_id, portfolio_id) {
  return await db.tx(async (tx) => {
    const owned = await tx.query(sql`
        SELECT id, cash_balance 
        FROM Portfolios
        WHERE id = ${portfolio_id} AND user_id = ${user_id};
      `);

    if (owned.length !== 1) {
      throw new Error("Invalid portfolio");
    }

    return await tx.query(sql`
      SELECT stock_symbol, num_shares
      FROM PortfolioHoldings
      WHERE portfolio_id=${portfolio_id};
    `);
  });
}

export async function purchaseShares(user_id, portfolio_id, stock_symbol, num_shares, share_price) {
  const cost = num_shares * share_price;

  await db.tx(async (tx) => {
    const owned = await tx.query(sql`
        SELECT id, cash_balance 
        FROM Portfolios
        WHERE id = ${portfolio_id} AND user_id = ${user_id};
      `);

    if (owned.length !== 1) {
      throw new Error("Invalid portfolio");
    }

    if (Number(owned[0].cash_balance) < cost) {
      throw new Error("Insufficient cash balance");
    }

    await tx.query(sql`
      UPDATE Portfolios
      SET cash_balance = cash_balance - ${cost}
      WHERE id = ${portfolio_id};
    `);

    await tx.query(sql`
      INSERT INTO PortfolioHoldings (portfolio_id, stock_symbol, num_shares)
      VALUES (${portfolio_id}, ${stock_symbol}, ${num_shares})
      ON CONFLICT (portfolio_id, stock_symbol)
      DO UPDATE SET num_shares = PortfolioHoldings.num_shares + EXCLUDED.num_shares;
    `);
  });
}

export async function sellShares(user_id, portfolio_id, stock_symbol, num_shares, share_price) {
  const price = num_shares * share_price;

  await db.tx(async (tx) => {
    const owned = await tx.query(sql`
        SELECT id, cash_balance 
        FROM Portfolios
        WHERE id = ${portfolio_id} AND user_id = ${user_id};
      `);

    if (owned.length !== 1) {
      throw new Error("Invalid portfolio");
    }

    const holding = await tx.query(sql`
        SELECT num_shares
        FROM PortfolioHoldings
        WHERE portfolio_id = ${portfolio_id} AND stock_symbol = ${stock_symbol};
      `);

    if (holding.length !== 1 || Number(holding[0].num_shares) < num_shares) {
      throw new Error("Not enough shares");
    }

    if (Number(holding[0].num_shares) === num_shares) {
      await tx.query(sql`
        DELETE FROM PortfolioHoldings
        WHERE 
          portfolio_id = ${portfolio_id} AND 
          stock_symbol = ${stock_symbol};
      `);
    } else {
      await tx.query(sql`
        UPDATE PortfolioHoldings
        SET num_shares = num_shares - ${num_shares}
        WHERE 
          portfolio_id = ${portfolio_id} AND
          stock_symbol = ${stock_symbol};
      `);
    }
    await tx.query(sql`
      UPDATE Portfolios
      SET cash_balance = cash_balance + ${price}
      WHERE id = ${portfolio_id};
    `);
  });
}
