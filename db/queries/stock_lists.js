import connect, { sql } from "@databases/pg";

const db = connect();

/*
CREATE TABLE IF NOT EXISTS StockLists (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES Users(id),
  label VARCHAR(128) NOT NULL,
  is_public BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS StockListHoldings (
  stock_list_id INTEGER NOT NULL REFERENCES StockLists(id) ON DELETE CASCADE,
  stock_symbol VARCHAR(16) NOT NULL REFERENCES Stocks(symbol),
  num_shares NUMERIC(20, 6) NOT NULL,
  PRIMARY KEY (stock_list_id, stock_symbol),
  CHECK (num_shares > 0)
);
*/

export async function getMyStockLists(user_id) {
  return await db.query(sql`
    SELECT id, label, is_public
    FROM StockLists
    WHERE user_id=${user_id};
    `);
}

export async function getPublicStockLists() {
  return await db.query(sql`
    SELECT id, user_id, label, is_public
    FROM StockLists
    WHERE is_public IS TRUE;
    `);
}

export async function getSharedStockLists(user_id) {
  return await db.query(sql`
    SELECT StockLists.id, StockLists.user_id, StockLists.label, StockLists.is_public
    FROM StockLists
    JOIN StockListShares ON StockLists.id=StockListShares.stock_list_id
    WHERE StockListShares.recipient_user_id=${user_id};
    `);
}

export async function getViewableStockLists(user_id) {
  return await db.query(sql`
    SELECT id, user_id, label, is_public
    FROM StockLists
    WHERE is_public IS TRUE

    UNION

    SELECT StockLists.id, StockLists.user_id, StockLists.label, StockLists.is_public
    FROM StockLists
    JOIN StockListShares ON StockLists.id=StockListShares.stock_list_id
    WHERE StockListShares.recipient_user_id=${user_id}

    UNION 

    SELECT id, user_id, label, is_public
    FROM StockLists
    WHERE user_id=${user_id};
    `);
}

export async function createStockList(user_id, label, is_public) {
  return await db.query(sql`
    INSERT INTO StockLists (user_id, label, is_public)
    VALUES (${user_id}, ${label}, ${is_public})
    `);
}

export async function getStockList(user_id, stock_list_id) {
  return await db.tx(async (tx) => {
    const viewableStockLists = await getViewableStockLists(user_id);

    if (!viewableStockLists.some((list) => Number(list.id) === Number(stock_list_id))) {
      throw new Error("Invalid stock list");
    }

    return await tx.query(sql`
      SELECT l.id, l.user_id, l.is_public, h.stock_symbol, h.num_shares
      FROM StockLists l
      LEFT JOIN StockListHoldings h 
      ON l.id = h.stock_list_id
      WHERE l.id=${stock_list_id};
      `);
  });
}

export async function deleteStockList(user_id, stock_list_id) {
  return await db.tx(async (tx) => {
    const owned = await tx.query(sql`
          SELECT id
          FROM StockLists
          WHERE 
            user_id = ${user_id} AND
            id = ${stock_list_id};
        `);

    if (owned.length !== 1) {
      throw new Error("Invalid stock list");
    }

    return await tx.query(sql`
        DELETE FROM StockLists
        WHERE id = ${stock_list_id};
        `);
  });
}

export async function changeStockListPublicStatus(user_id, stock_list_id, is_public) {
  return await db.tx(async (tx) => {
    const owned = await tx.query(sql`
          SELECT id
          FROM StockLists
          WHERE 
            user_id = ${user_id} AND
            id = ${stock_list_id};
        `);

    if (owned.length !== 1) {
      throw new Error("Invalid stock list");
    }

    return await tx.query(sql`
        UPDATE StockLists 
        SET is_public = ${is_public}
        WHERE id = ${stock_list_id};
        `);
  });
}
